// Generates an evenly distributed dot-matrix land mask for the canvas globe.
// Source: Natural Earth 110m land (public domain) - ne_110m_land.geojson
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const geo = JSON.parse(
  readFileSync(resolve(__dirname, "land.geojson"), "utf8"),
);

/** @typedef {[number, number]} Point */
/** @type {{bbox: [number, number, number, number], rings: Point[][]}[]} */
const polygons = [];

for (const feature of geo.features) {
  const geometry = feature.geometry;
  const coordinates =
    geometry.type === "Polygon" ? [geometry.coordinates] : geometry.coordinates;

  for (const polygon of coordinates) {
    const rings = polygon.map((ring) => ring.map(([lon, lat]) => [lon, lat]));
    let minLon = 180;
    let minLat = 90;
    let maxLon = -180;
    let maxLat = -90;
    for (const ring of rings) {
      for (const [lon, lat] of ring) {
        if (lon < minLon) minLon = lon;
        if (lon > maxLon) maxLon = lon;
        if (lat < minLat) minLat = lat;
        if (lat > maxLat) maxLat = lat;
      }
    }
    polygons.push({ bbox: [minLon, minLat, maxLon, maxLat], rings });
  }
}

/** @param {number} lon @param {number} lat @param {Point[]} ring */
function pointInRing(lon, lat, ring) {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i];
    const [xj, yj] = ring[j];
    if (
      yi > lat !== yj > lat &&
      lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi
    ) {
      inside = !inside;
    }
  }
  return inside;
}

/** @param {number} lon @param {number} lat */
function isLand(lon, lat) {
  for (const polygon of polygons) {
    const [minLon, minLat, maxLon, maxLat] = polygon.bbox;
    if (lon < minLon || lon > maxLon || lat < minLat || lat > maxLat) continue;
    if (!pointInRing(lon, lat, polygon.rings[0])) continue;
    let inHole = false;
    for (let r = 1; r < polygon.rings.length; r++) {
      if (pointInRing(lon, lat, polygon.rings[r])) {
        inHole = true;
        break;
      }
    }
    if (!inHole) return true;
  }
  return false;
}

const STEP = 1.8;
const points = [];
const round = (value) => Math.round(value * 100) / 100;

for (let lat = -58; lat <= 84; lat += STEP) {
  const lonStep = STEP / Math.max(0.22, Math.cos((lat * Math.PI) / 180));
  for (let lon = -180; lon < 180; lon += lonStep) {
    if (isLand(lon, lat)) points.push([round(lat), round(lon)]);
  }
}

const output = `// AUTO-GENERATED by scripts/generate-land-points.mjs
// Natural Earth 110m land mask sampled as an evenly spaced dot grid.
// Each tuple is [latitude, longitude].

export const LAND_POINTS: ReadonlyArray<readonly [number, number]> = ${JSON.stringify(
  points,
)};
`;

writeFileSync(resolve(__dirname, "../src/lib/land-points.ts"), output);
console.log(
  `Generated ${points.length} land points (${(output.length / 1024).toFixed(1)} KB)`,
);
